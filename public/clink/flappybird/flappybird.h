/**
 * Run the full iterated function R1CS proof using A12 protocol
 * for Flappy Bird DQN + Environment.
 */
inline void IteratedFunctionProof(size_t max_steps,
                                  std::string const& data_dir = "") {
  IteratedFunctionProofStats stats;
  auto total_start = std::chrono::high_resolution_clock::now();

  namespace fp = circuit::fp;
  fp::RationalConst<8, 24> rc;

  FlappyBird::Para para;
  FlappyBird::LoadPara(para, data_dir);

  // ========== 1. Create protoboard and gadget ==========
  libsnark::protoboard<Fr> pb;
  DqnEnvGadgetVars vars;
  auto gadget_ptr = CreateDqnEnvGadget(pb, vars, "DqnEnvGadget");
  auto& gadget = *gadget_ptr;

  SparseMatrix sparse_a, sparse_b, sparse_c;
  circuit::PreprocessSparse(pb, sparse_a, sparse_b, sparse_c);

  auto r1cs_stats = circuit::GetR1csStats(sparse_a, sparse_b, sparse_c);
  std::cout << "R1CS: " << r1cs_stats.num_constraints << " constraints, "
            << r1cs_stats.num_variables << " variables\n";

  // ========== 1.5 Separate DQN, Env, and Render constraint counting ==========
  {
    // DQN only protoboard
    libsnark::protoboard<Fr> pb_dqn;
    libsnark::pb_variable_array<Fr> dqn_image;
    dqn_image.allocate(pb_dqn, circuit::flappybird::DqnGadget<8, 24>::IMG_SIZE, "dqn_image");
    libsnark::pb_variable_array<Fr> dqn_conv1_w, dqn_conv2_w, dqn_conv3_w, dqn_fc1_w, dqn_fc2_w;
    dqn_conv1_w.allocate(pb_dqn, circuit::flappybird::DqnGadget<8, 24>::conv1_weight_size(), "dqn_conv1_w");
    dqn_conv2_w.allocate(pb_dqn, circuit::flappybird::DqnGadget<8, 24>::conv2_weight_size(), "dqn_conv2_w");
    dqn_conv3_w.allocate(pb_dqn, circuit::flappybird::DqnGadget<8, 24>::conv3_weight_size(), "dqn_conv3_w");
    dqn_fc1_w.allocate(pb_dqn, circuit::flappybird::DqnGadget<8, 24>::fc1_weight_size(), "dqn_fc1_w");
    dqn_fc2_w.allocate(pb_dqn, circuit::flappybird::DqnGadget<8, 24>::fc2_weight_size(), "dqn_fc2_w");
    circuit::flappybird::DqnGadget<8, 24> dqn_only(
        pb_dqn, dqn_image, dqn_conv1_w, dqn_conv2_w, dqn_conv3_w, dqn_fc1_w, dqn_fc2_w, "DqnOnly");
    size_t dqn_constraints = pb_dqn.num_constraints();
    size_t dqn_variables = pb_dqn.num_variables();

    // Env only protoboard
    libsnark::protoboard<Fr> pb_env;
    libsnark::pb_variable_array<Fr> env_in_state;
    env_in_state.allocate(pb_env, circuit::flappybird::EnvGadget::STATE_DIM, "env_in_state");
    libsnark::pb_variable<Fr> env_action;
    env_action.allocate(pb_env, "env_action");
    libsnark::pb_variable<Fr> env_next_gap_y;
    env_next_gap_y.allocate(pb_env, "env_next_gap_y");
    libsnark::linear_combination<Fr> env_action_lc(env_action);
    circuit::flappybird::EnvGadget env_only(
        pb_env, env_in_state, env_action_lc, env_next_gap_y, "EnvOnly");
    size_t env_constraints = pb_env.num_constraints();
    size_t env_variables = pb_env.num_variables();

    // Render only protoboard
    libsnark::protoboard<Fr> pb_render;
    libsnark::pb_variable_array<Fr> render_state;
    render_state.allocate(pb_render, 7, "render_state");  // RenderGadget uses state[0..6]
    circuit::flappybird::RenderGadget render_only(pb_render, render_state, "RenderOnly");
    size_t render_constraints = pb_render.num_constraints();
    size_t render_variables = pb_render.num_variables();

    // Print DQN, Env, and Render statistics
    std::cout << "\n========== Circuit Component Statistics ==========\n";
    std::cout << "DQN (Neural Network Inference):\n";
    std::cout << "  Constraints: " << dqn_constraints << "\n";
    std::cout << "  Variables:   " << dqn_variables << "\n";
    std::cout << "Env (State Transition):\n";
    std::cout << "  Constraints: " << env_constraints << "\n";
    std::cout << "  Variables:   " << env_variables << "\n";
    std::cout << "Render (Image Rendering):\n";
    std::cout << "  Constraints: " << render_constraints << "\n";
    std::cout << "  Variables:   " << render_variables << "\n";
    std::cout << "Total (DQN + Env + Render + packing):\n";
    std::cout << "  Constraints: " << (dqn_constraints + env_constraints + render_constraints) << " (plus packing constraints)\n";
    std::cout << "  Variables:   " << (dqn_variables + env_variables + render_variables) << " (plus shared variables)\n";
    std::cout << "==================================================\n\n";
  }

  int64_t num_constraints = r1cs_stats.num_constraints;
  // r1cs_stats.num_variables = mat_a.cols() = pb.num_variables() + 1 (includes "one" variable)
  // Use pb.num_variables() directly to avoid off-by-one confusion
  int64_t num_variables = static_cast<int64_t>(pb.num_variables());
  stats.num_constraints = num_constraints;
  stats.num_vars = num_variables;

  // Copy constraint indices
  // in_state and prev_images are allocated contiguously, out_state/out_image may not be
  size_t in_start_idx = vars.in_state[0].index;
  size_t out_start_idx = gadget.out_state()[0].index;
  size_t prev_images_start_idx = vars.prev_images[0].index;
  size_t out_image_start_idx = gadget.out_image()[0].index;
  constexpr int IMG_84 = 84 * 84;  // 7056 pixels per frame

  // ========== 2. Generate trajectory (directly into column-major layout) ==========
  auto traj_start = std::chrono::high_resolution_clock::now();
  int64_t total_vars = num_variables + 1;

  // Pre-allocate flat_row_z with max_steps columns to avoid row_z intermediate storage.
  // This eliminates the transpose phase and its 2x peak memory overhead.
  FlatMatrix flat_row_z(total_vars, static_cast<int64_t>(max_steps));
  size_t actual_steps = 0;

  // Assign CNN weights once
  AssignWeights(pb, vars.conv1_weights, para.conv1);
  AssignWeights(pb, vars.conv2_weights, para.conv2);
  AssignWeights(pb, vars.conv3_weights, para.conv3);
  AssignWeights(pb, vars.fc1_weights, para.fc1);
  AssignWeights(pb, vars.fc2_weights, para.fc2);

  // Initial state: bird at center, no velocity, pipes at right edge
  // gap_y range in Python: rng.randint(2,10)*10 + int(404/5) = 100~180
  std::vector<Fr> state = {
      Fr(244),   // bird_y = (512-24)/2 = 244 (center)
      Fr(0),     // bird_vy = 0
      Fr(288),   // pipe1_x = SCREEN_WIDTH
      Fr(140),   // pipe1_gap_y (within Python range 100~180)
      Fr(432),   // pipe2_x = SCREEN_WIDTH * 3/2
      Fr(160),   // pipe2_gap_y (within Python range 100~180)
      Fr(0),     // score = 0
      Fr(0)      // terminal = 0 (game not over)
  };

  // Previous 3 frames (initially all zeros)
  constexpr int PREV_IMAGES_SIZE = 3 * 84 * 84;
  std::vector<Fr> prev_images(PREV_IMAGES_SIZE, Fr(0));

#ifdef DEBUG
  // Game record for replay
  using json = nlohmann::json;
  json game_record;
  game_record["seed"] = 0;  // deterministic mode, no random seed
  game_record["initial_state"] = json::array();
  for (int i = 0; i < circuit::flappybird::EnvGadget::STATE_DIM; ++i) {
    game_record["initial_state"].push_back(state[i].getInt64());
  }
  game_record["steps"] = json::array();
#endif

  for (size_t step = 0; step < max_steps; ++step) {
    // Assign input state
    for (int i = 0; i < circuit::flappybird::EnvGadget::STATE_DIM; ++i) {
      pb.val(vars.in_state[i]) = state[i];
    }

    // Assign previous images (parallelized)
    auto assign_prev_images = [&](int64_t i) {
      pb.val(vars.prev_images[i]) = prev_images[i];
    };
    parallel::For(static_cast<int64_t>(PREV_IMAGES_SIZE), assign_prev_images);

    // Assign next_gap_y (deterministic, matching Python range: randint(2,10)*10 + 80)
    // Python range: 100~180. Use deterministic sequence within this range.
    int64_t next_gap_y_val = 100 + static_cast<int64_t>((step * 37 + 17) % 9) * 10;
    pb.val(vars.next_gap_y) = Fr(next_gap_y_val);

    // Run the full DQN + Env pipeline
    gadget.generate_r1cs_witness();

#ifdef DEBUG_CHECK_R1CS
    assert(pb.is_satisfied());
#endif

    // Write assignment directly into flat_row_z column (column-major layout).
    // This avoids allocating a separate row_z vector and the subsequent transpose.
    int64_t col_idx = static_cast<int64_t>(step);
    auto const& full_assignment = pb.full_variable_assignment();
    flat_row_z(0, col_idx) = FrOne();
    auto collect_assignment = [&](int64_t i) {
      flat_row_z(i + 1, col_idx) = full_assignment[i];
    };
    parallel::For(num_variables, collect_assignment);
    actual_steps = step + 1;

    // Read output state
    std::vector<Fr> out_state(circuit::flappybird::EnvGadget::STATE_DIM);
    for (int i = 0; i < circuit::flappybird::EnvGadget::STATE_DIM; ++i) {
      out_state[i] = pb.val(gadget.out_state()[i]);
    }

    int64_t in_by = state[0].getInt64();
    int64_t out_by = out_state[0].getInt64();
    int64_t in_vy = state[1].getInt64();
    int64_t out_vy = out_state[1].getInt64();

    int action = gadget.get_dqn_action_index();
    auto [q0, q1] = gadget.get_dqn_q_values();

#ifdef DEBUG
    std::cout << "Step " << step << ": bird_y=" << in_by
              << " vel=" << in_vy << " action=" << action
              << " -> bird_y=" << out_by << " vel=" << out_vy << "\n";

    // Record step for game replay
    {
      json step_record;
      step_record["step"] = step;
      step_record["state"] = json::array();
      for (int i = 0; i < circuit::flappybird::EnvGadget::STATE_DIM; ++i) {
        step_record["state"].push_back(state[i].getInt64());
      }
      step_record["dqn_action"] = action;
      step_record["next_gap_y"] = next_gap_y_val;
      step_record["next_state"] = json::array();
      for (int i = 0; i < circuit::flappybird::EnvGadget::STATE_DIM; ++i) {
        step_record["next_state"].push_back(out_state[i].getInt64());
      }
      step_record["is_terminal"] = is_terminal;
      game_record["steps"].push_back(step_record);
    }
#endif

    bool is_terminal = circuit::flappybird::EnvGadget::IsTerminal(out_state);

    // Update previous images: shift frames and add current rendered image
    // Must shift in order to avoid data race: frame0 reads frame1, frame1 reads frame2
    auto const& cur_image = gadget.out_image();
    constexpr int IMG_84 = 84 * 84;
    // Step 1: frame[0] = old frame[1] (safe: no concurrent write to frame1)
    auto copy_frame0 = [&](int64_t i) {
      prev_images[i] = prev_images[IMG_84 + i];
    };
    parallel::For(static_cast<int64_t>(IMG_84), copy_frame0);
    // Step 2: frame[1] = old frame[2] (safe: frame0 copy already done)
    auto copy_frame1 = [&](int64_t i) {
      prev_images[IMG_84 + i] = prev_images[2 * IMG_84 + i];
    };
    parallel::For(static_cast<int64_t>(IMG_84), copy_frame1);
    // Step 3: frame[2] = current rendered image
    auto copy_new_frame = [&](int64_t i) {
      prev_images[2 * IMG_84 + i] = pb.val(cur_image[i]);
    };
    parallel::For(static_cast<int64_t>(IMG_84), copy_new_frame);

    // Use output state as next input
    state = out_state;

    // Check terminal
    // if (is_terminal) {
    //   std::cout << "Terminal state reached at step " << step + 1 << "\n";
    //   break;
    // }
  }
  auto traj_end = std::chrono::high_resolution_clock::now();
  stats.trajectory_gen_ms =
      std::chrono::duration<double, std::milli>(traj_end - traj_start).count();

  stats.num_instances = actual_steps;
  std::cout << "Generated " << stats.num_instances << " valid steps.\n";

  // Shrink flat_row_z to actual number of steps if terminated early
  if (static_cast<int64_t>(actual_steps) < static_cast<int64_t>(max_steps)) {
    FlatMatrix trimmed(total_vars, static_cast<int64_t>(actual_steps));
    auto copy_col = [&](int64_t i) {
      for (int64_t j = 0; j < static_cast<int64_t>(actual_steps); ++j) {
        trimmed(i, j) = flat_row_z(i, j);
      }
    };
    parallel::For(total_vars, copy_col);
    flat_row_z = std::move(trimmed);
  }

#ifdef DEBUG
  // Save game record
  game_record["total_steps"] = stats.num_instances;
  game_record["final_state"] = json::array();
  for (int i = 0; i < circuit::flappybird::EnvGadget::STATE_DIM; ++i) {
    game_record["final_state"].push_back(state[i].getInt64());
  }
  {
    std::string record_path = "data/flappybird/dqn_env_game_record.json";
    std::ifstream test_dir("data/flappybird");
    if (!test_dir.is_open()) {
      record_path = "../data/flappybird/dqn_env_game_record.json";
    }
    std::ofstream record_file(record_path);
    if (record_file.is_open()) {
      record_file << game_record.dump(2);
      std::cout << "Game record saved to: " << record_path << "\n";
    } else {
      std::cerr << "Warning: could not save game record to " << record_path << "\n";
    }
  }
#endif
  CHECK(stats.num_instances >= 2, "Need at least 2 steps for A12 proof");

  // No separate transpose phase needed - data is already in column-major layout
  stats.matrix_transpose_ms = 0.0;

  // Build copy constraint ranges for step j -> step j+1:
  //   1. State copy: out_state[0..7] -> in_state[0..7]
  //   2. Frame shift: prev_images[frame1] -> prev_images[frame0]  (7056 pixels)
  //   3. Frame shift: prev_images[frame2] -> prev_images[frame1]  (7056 pixels)
  //   4. New frame:   out_image[0..7055] -> prev_images[frame2]   (7056 pixels)
  constexpr int STATE_DIM = circuit::flappybird::EnvGadget::STATE_DIM;
  int64_t prev_frame0_start = static_cast<int64_t>(prev_images_start_idx);
  int64_t prev_frame1_start = static_cast<int64_t>(prev_images_start_idx + IMG_84);
  int64_t prev_frame2_start = static_cast<int64_t>(prev_images_start_idx + 2 * IMG_84);

  std::vector<argument::CopyRange> copy_ranges;
  // CopyRange(l_a, l_b, l): A12 semantics is z_j[l_a..l_a+l-1] == z_{j+1}[l_b..l_b+l-1]
  // State: step j's out_state -> step j+1's in_state
  copy_ranges.emplace_back(
      static_cast<int64_t>(out_start_idx),
      static_cast<int64_t>(in_start_idx),
      static_cast<int64_t>(STATE_DIM));
  // Frame shift: step j's prev_images[frame1] -> step j+1's prev_images[frame0]
  copy_ranges.emplace_back(
      prev_frame1_start, prev_frame0_start, static_cast<int64_t>(IMG_84));
  // Frame shift: step j's prev_images[frame2] -> step j+1's prev_images[frame1]
  copy_ranges.emplace_back(
      prev_frame2_start, prev_frame1_start, static_cast<int64_t>(IMG_84));
  // New frame: step j's out_image -> step j+1's prev_images[frame2]
  copy_ranges.emplace_back(
      static_cast<int64_t>(out_image_start_idx),
      prev_frame2_start,
      static_cast<int64_t>(IMG_84));


#ifdef DEBUG
  // ========== 4a. Direct R1CS + Copy Constraint Verification (debug only) ==========
  {
    std::cout << "\n=== Verifying R1CS constraints (DEBUG) ===\n";
    bool all_satisfied = true;

    for (size_t j = 0; j < stats.num_instances; ++j) {
      std::vector<Fr> z_j = flat_row_z.col(static_cast<int64_t>(j));
      bool step_satisfied = true;
      int64_t violated_count = 0;

      // Use std::vector<int> to avoid std::vector<bool> bit-packing data race
      std::vector<int> constraint_results(num_constraints, 1);
      auto verify_constraint = [&](int64_t i) {
        Fr az = FrZero();
        for (int64_t k = sparse_a.row_ptr_[i]; k < sparse_a.row_ptr_[i + 1]; ++k)
          az += sparse_a.values_[k] * z_j[sparse_a.col_idx_[k]];
        Fr bz = FrZero();
        for (int64_t k = sparse_b.row_ptr_[i]; k < sparse_b.row_ptr_[i + 1]; ++k)
          bz += sparse_b.values_[k] * z_j[sparse_b.col_idx_[k]];
        Fr cz = FrZero();
        for (int64_t k = sparse_c.row_ptr_[i]; k < sparse_c.row_ptr_[i + 1]; ++k)
          cz += sparse_c.values_[k] * z_j[sparse_c.col_idx_[k]];
        constraint_results[i] = (az * bz == cz) ? 1 : 0;
      };
      parallel::For(num_constraints, verify_constraint);

      for (int64_t i = 0; i < num_constraints; ++i) {
        if (constraint_results[i] == 0) {
          step_satisfied = false;
          violated_count++;
          if (violated_count <= 5)
            std::cout << "  R1CS violation at step " << j << " constraint " << i << "\n";
        }
      }
      if (step_satisfied) {
        std::cout << "Step " << j << ": R1CS satisfied (" << num_constraints << " constraints)\n";
      } else {
        std::cout << "Step " << j << ": R1CS VIOLATED (" << violated_count
                  << " / " << num_constraints << " constraints failed)\n";
        all_satisfied = false;
      }
    }

    std::cout << "\n=== Verifying copy constraints (DEBUG) ===\n";
    std::string range_names[] = {"state", "prev_frame0<-frame1", "prev_frame1<-frame2", "prev_frame2<-out_image"};
    for (size_t j = 0; j + 1 < stats.num_instances; ++j) {
      bool copy_ok = true;
      for (size_t r = 0; r < copy_ranges.size(); ++r) {
        auto const& range = copy_ranges[r];
        int64_t violated = 0;
        for (int64_t k = 0; k < range.l; ++k) {
          Fr src_val = flat_row_z(range.l_a + k, static_cast<int64_t>(j));
          Fr dst_val = flat_row_z(range.l_b + k, static_cast<int64_t>(j + 1));
          if (src_val != dst_val) {
            violated++;
            if (violated <= 3)
              std::cout << "  Copy violated: step " << j << "->" << (j + 1)
                        << " range[" << range_names[r] << "] offset " << k << "\n";
            copy_ok = false;
            all_satisfied = false;
          }
        }
        if (violated > 0)
          std::cout << "  Range " << range_names[r] << ": " << violated
                    << " / " << range.l << " mismatches\n";
      }
      if (copy_ok)
        std::cout << "Step " << j << " -> " << (j + 1) << ": all copy constraints satisfied\n";
    }

    std::cout << "\nDirect Verify: " << (all_satisfied ? "PASS" : "FAIL") << "\n";
    CHECK(all_satisfied, "Direct R1CS + copy constraint verification failed");
  }
#endif

  // ========== 4b. A12 prove/verify ==========
  h256_t seed = misc::RandH256();
  argument::A12::SparseProveInput prove_input(
      sparse_a, sparse_b, sparse_c, flat_row_z, copy_ranges, pc::kGetRefG1);

  auto prove_total_start = std::chrono::high_resolution_clock::now();

  auto com_start = std::chrono::high_resolution_clock::now();
  argument::A12::CommitmentPub com_pub;
  argument::A12::CommitmentSec com_sec;
  argument::A12::ComputeCom(com_pub, com_sec, prove_input);
  auto com_end = std::chrono::high_resolution_clock::now();
  stats.compute_com_ms =
      std::chrono::duration<double, std::milli>(com_end - com_start).count();

  stats.com_g1_count = com_pub.com_z.size();

  auto prove_start = std::chrono::high_resolution_clock::now();
  argument::A12::Proof proof;
  argument::A12::ProveIf(proof, seed, prove_input, com_pub, com_sec);
  auto prove_end = std::chrono::high_resolution_clock::now();
  stats.prove_ms =
      std::chrono::duration<double, std::milli>(prove_end - prove_start).count();

  auto prove_total_end = std::chrono::high_resolution_clock::now();
  stats.prove_total_ms = stats.trajectory_gen_ms +
      std::chrono::duration<double, std::milli>(prove_total_end - prove_total_start).count();

  stats.proof_fr_size = proof.FrSize();
  stats.proof_g1_size = proof.G1Size();

  // Serialize commitment to get size
  yas::mem_ostream com_os;
  yas::binary_oarchive<yas::mem_ostream, YasBinF()> com_oa(com_os);
  com_oa.serialize(com_pub);
  stats.com_serialized_size = com_os.get_shared_buffer().size;

  // Serialize proof to get size
  yas::mem_ostream proof_os;
  yas::binary_oarchive<yas::mem_ostream, YasBinF()> proof_oa(proof_os);
  proof_oa.serialize(proof);
  stats.proof_serialized_size = proof_os.get_shared_buffer().size;

  stats.total_proof_size = stats.com_serialized_size + stats.proof_serialized_size;

  auto verify_total_start = std::chrono::high_resolution_clock::now();
  auto verify_start = std::chrono::high_resolution_clock::now();
  argument::A12::SparseVerifyInput verify_input(
      sparse_a, sparse_b, sparse_c, com_pub, stats.num_instances,
      copy_ranges, pc::kGetRefG1);
  stats.verify_success = argument::A12::VerifyIf(proof, seed, verify_input);
  auto verify_end = std::chrono::high_resolution_clock::now();
  stats.verify_ms =
      std::chrono::duration<double, std::milli>(verify_end - verify_start).count();
  auto verify_total_end = std::chrono::high_resolution_clock::now();
  stats.verify_total_ms =
      std::chrono::duration<double, std::milli>(verify_total_end - verify_total_start).count();

  auto total_end = std::chrono::high_resolution_clock::now();
  stats.total_ms =
      std::chrono::duration<double, std::milli>(total_end - total_start).count();

  stats.max_steps = max_steps;
  stats.peak_memory_mb = misc::GetPeakMemoryByPid(getpid()) / 1024.0;

  CHECK(stats.verify_success, "A12 verify failed");

  stats.print();
}

