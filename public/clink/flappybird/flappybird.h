/**
 * Read a CSV file of fixed-point integers into a 2D vector of Fr.
 * Each row in the CSV becomes a row in the result.
 * Values are already in fixed-point format (value * 2^24).
 */
inline std::vector<std::vector<Fr>> ReadWeightCsv(
    std::string const& filepath) {
  std::ifstream file(filepath);
  CHECK(file.is_open(), "Cannot open weight file: " << filepath);

  std::vector<std::vector<Fr>> result;
  std::string line;
  while (std::getline(file, line)) {
    if (line.empty()) continue;
    std::vector<Fr> row;
    std::istringstream stream(line);
    std::string token;
    while (std::getline(stream, token, ',')) {
      int64_t value = std::stoll(token);
      row.push_back(Fr(value));
    }
    result.push_back(std::move(row));
  }
  return result;
}

/**
 * Transpose a 2D weight matrix: [rows][cols] -> [cols][rows]
 */
inline std::vector<std::vector<Fr>> TransposeWeights(
    std::vector<std::vector<Fr>> const& matrix) {
  if (matrix.empty()) return {};
  size_t rows = matrix.size();
  size_t cols = matrix[0].size();
  std::vector<std::vector<Fr>> transposed(cols, std::vector<Fr>(rows));
  for (size_t r = 0; r < rows; ++r) {
    for (size_t c = 0; c < cols; ++c) {
      transposed[c][r] = matrix[r][c];
    }
  }
  return transposed;
}

struct FlappyBird {
  struct Para {
    // Conv1: Conv2d(4, 32, kernel=8, stride=4)
    // Shape: [32][4*8*8 + 1] = [32][257]
    std::vector<std::vector<Fr>> conv1;

    // Conv2: Conv2d(32, 64, kernel=4, stride=2)
    // Shape: [64][32*4*4 + 1] = [64][513]
    std::vector<std::vector<Fr>> conv2;

    // Conv3: Conv2d(64, 64, kernel=3, stride=1)
    // Shape: [64][64*3*3 + 1] = [64][577]
    std::vector<std::vector<Fr>> conv3;

    // FC1: Linear(3136, 512)
    // Shape: [3136 + 1][512] = [3137][512]
    std::vector<std::vector<Fr>> fc1;

    // FC2: Linear(512, 2)
    // Shape: [512 + 1][2] = [513][2]
    std::vector<std::vector<Fr>> fc2;
  };

  /**
   * Load CNN model parameters from CSV files.
   * CSV files are generated by extract_flappybird_weights.py.
   * Values are stored as fixed-point integers (value * 2^24).
   *
   * @param data_dir  Directory containing the CSV files
   *                  (default: "data/flappybird" relative to project root)
   */
  static void LoadPara(Para& para,
                       std::string const& data_dir = "") {
    Tick tick(__FN__);

    // Auto-detect data directory: try "data/flappybird" then "../data/flappybird"
    std::string resolved_dir = data_dir;
    if (resolved_dir.empty()) {
      std::ifstream test_file("data/flappybird/conv1_weights.csv");
      if (test_file.is_open()) {
        resolved_dir = "data/flappybird";
      } else {
        std::ifstream test_file2("../data/flappybird/conv1_weights.csv");
        CHECK(test_file2.is_open(),
              "Cannot find data directory. Run from project root or pod_dummy/");
        resolved_dir = "../data/flappybird";
      }
      std::cout << "Using data directory: " << resolved_dir << "\n";
    }

    para.conv1 = ReadWeightCsv(resolved_dir + "/conv1_weights.csv");
    CHECK(para.conv1.size() == 32 && para.conv1[0].size() == 257,
          "conv1 shape mismatch: expected [32][257], got ["
              << para.conv1.size() << "][" << para.conv1[0].size() << "]");

    para.conv2 = ReadWeightCsv(resolved_dir + "/conv2_weights.csv");
    CHECK(para.conv2.size() == 64 && para.conv2[0].size() == 513,
          "conv2 shape mismatch: expected [64][513], got ["
              << para.conv2.size() << "][" << para.conv2[0].size() << "]");

    para.conv3 = ReadWeightCsv(resolved_dir + "/conv3_weights.csv");
    CHECK(para.conv3.size() == 64 && para.conv3[0].size() == 577,
          "conv3 shape mismatch: expected [64][577], got ["
              << para.conv3.size() << "][" << para.conv3[0].size() << "]");

    // fc1 and fc2 CSV files: [out_dim][in_dim+1] (same as conv layers)
    para.fc1 = ReadWeightCsv(resolved_dir + "/fc1_weights.csv");
    CHECK(para.fc1.size() == 512 && para.fc1[0].size() == 3137,
          "fc1 shape mismatch: expected [512][3137], got ["
              << para.fc1.size() << "][" << para.fc1[0].size() << "]");

    para.fc2 = ReadWeightCsv(resolved_dir + "/fc2_weights.csv");
    CHECK(para.fc2.size() == 2 && para.fc2[0].size() == 513,
          "fc2 shape mismatch: expected [2][513], got ["
              << para.fc2.size() << "][" << para.fc2[0].size() << "]");

    std::cout << "Loaded CNN weights: conv1[32x257] conv2[64x513] "
              << "conv3[64x577] fc1[512x3137] fc2[2x513]\n";
  }
};

